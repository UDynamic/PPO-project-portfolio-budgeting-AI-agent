# ── main ───────────────────────────────────────────────────────────────────────
def main():
    if not XLSX.exists():
        sys.exit(f"Cannot find {XLSX}  —  place env_config_matrix.xlsx next to this script.")

    wb = openpyxl.load_workbook(XLSX, data_only=True)
    if "CONFIGS" not in wb.sheetnames:
        sys.exit("Workbook has no sheet named CONFIGS.")

    ws   = wb["CONFIGS"]
    rows = list(ws.iter_rows(min_row=3, values_only=True))

    OUT_DIR.mkdir(exist_ok=True)
    generated = []

    for row in rows:
        if row[0] is None:       # blank row
            continue

        config_id   = str(row[0]).strip()
        config_name = str(row[1]).strip()
        air         = to_float_or_none(row[2])   # annual_interest_rate

        # build flat dict of all dist/p1..p4 values
        kv = {"config_id": config_id, "config_name": config_name,
              "annual_interest_rate": air}

        col = 3   # 0-based offset after the 3 fixed columns
        for stem in PARAM_STEMS:
            dist = row[col];     col += 1
            p1   = row[col];     col += 1
            p2   = row[col];     col += 1
            p3   = row[col];     col += 1
            p4   = row[col];     col += 1

            kv[f"{stem}_dist"] = str(dist) if dist else "fixed"
            kv[f"{stem}_p1"]   = to_float_or_none(p1)
            kv[f"{stem}_p2"]   = to_float_or_none(p2)
            kv[f"{stem}_p3"]   = to_float_or_none(p3)
            kv[f"{stem}_p4"]   = to_float_or_none(p4)

        py_src = TEMPLATE.format(**kv)

        # safe filename: replace - with _ so it's a valid module name
        fname  = config_id.replace("-", "_") + ".py"
        fpath  = OUT_DIR / fname
        fpath.write_text(py_src, encoding="utf-8")
        generated.append(fname)

    print(f"Generated {len(generated)} config files in {OUT_DIR}/")
    for f in generated:
        print(f"  {f}")

if __name__ == "__main__":
    main()